"""Generate a LiteLLM proxy config.yaml from the public ArgoLink model catalog.

Standard library only (Python 3.9+). The catalog endpoint is public and needs no key.

    python scripts/gen_config.py > config.yaml                       # curated set, live catalog
    python scripts/gen_config.py --all-chat > config.all.yaml        # every chat model
    python scripts/gen_config.py --catalog tests/fixtures/catalog-2026-10-07.json

Provider prefix rule (checked against the model pages on 2026-10-07):
  * Anthropic models  -> anthropic/<id>, api_base https://argolink.io  (LiteLLM appends /v1/messages)
  * every other model -> openai/<id>,    api_base https://argolink.io/v1 (/v1/chat/completions, /v1/responses)
"""
from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from decimal import Decimal

CATALOG_URL = "https://argolink.io/api/catalog/v1/models?page_size=100"
OPENAI_BASE = "https://argolink.io/v1"
ANTHROPIC_BASE = "https://argolink.io"
KEY_ENV = "os.environ/UPSTREAM_API_KEY"

DEFAULT_MODELS = [
    "gpt-6-sol",
    "gpt-5.6-luna",
    "claude-opus-5",
    "claude-sonnet-5",
    "grok-4.6",
    "deepseek-v4-pro",
    "deepseek-v4.1-flash",
    "glm-5.3",
    "glm-5.3-flash",
    "kimi-k2.6",
]
# One model group served by two deployments, picked 3:1 by LiteLLM's weighted shuffle.
BUDGET_GROUP = [("deepseek-v4.1-flash", 3), ("glm-5.3-flash", 1)]
ALIASES = {"smart": "gpt-6-sol", "claude": "claude-opus-5", "cheap": "budget"}
FALLBACKS = [
    ("claude-opus-5", ["claude-sonnet-5", "gpt-6-sol"]),
    ("gpt-6-sol", ["claude-sonnet-5"]),
    ("deepseek-v4-pro", ["glm-5.3"]),
    ("budget", ["gpt-5.6-luna"]),
]


def load_catalog(path: str | None) -> dict:
    if path:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    # The CDN in front of the API rejects urllib's default "Python-urllib/x.y" agent (403, error 1010).
    request = urllib.request.Request(CATALOG_URL, headers={"User-Agent": "litellm-gateway-gen-config/1.0"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def per_token(per_million) -> str:
    """$ per 1M tokens -> $ per token, written out without exponent notation."""
    value = Decimal(str(per_million)) / Decimal(1_000_000)
    text = format(value.normalize(), "f")
    return text


def money(per_million) -> str:
    return f"${Decimal(str(per_million)).normalize():f}"


def deployment(model: dict, name: str | None = None, weight: int | None = None) -> list[str]:
    anthropic = model["provider_id"] == "anthropic"
    prefix, base = ("anthropic", ANTHROPIC_BASE) if anthropic else ("openai", OPENAI_BASE)
    eff = model["pricing"]["effective"]
    lines = [
        f"  # {model['display_name']}: {money(eff['input_per_million'])} in / {money(eff['output_per_million'])} out"
        " per 1M tokens on ArgoLink",
        f"  - model_name: {name or model['id']}",
        "    litellm_params:",
        f"      model: {prefix}/{model['id']}",
        f"      api_base: {base}",
        f"      api_key: {KEY_ENV}",
    ]
    if weight is not None:
        lines.append(f"      weight: {weight}")
    lines += [
        "    model_info:",
        f"      input_cost_per_token: {per_token(eff['input_per_million'])}",
        f"      output_cost_per_token: {per_token(eff['output_per_million'])}",
    ]
    if eff.get("cached_input_per_million"):
        lines.append(f"      cache_read_input_token_cost: {per_token(eff['cached_input_per_million'])}")
    if eff.get("cache_write_per_million"):
        lines.append(f"      cache_creation_input_token_cost: {per_token(eff['cache_write_per_million'])}")
    return lines


def render(catalog: dict, model_ids: list[str], with_budget_group: bool = True) -> str:
    by_id = {m["id"]: m for m in catalog["items"] if m.get("category") == "chat"}
    missing = [m for m in model_ids if m not in by_id]
    if missing:
        raise SystemExit(f"not in the catalog: {', '.join(missing)}")
    out = [
        "# LiteLLM proxy config for ArgoLink's OpenAI- and Anthropic-compatible endpoints.",
        f"# Generated by scripts/gen_config.py from catalog revision {catalog.get('revision', '?')}.",
        "# Costs are ArgoLink's per-token prices so LiteLLM's spend tracking matches the bill",
        "# (peak-hour, long-context and Fast-mode multipliers are not modelled; see README).",
        "model_list:",
    ]
    for model_id in model_ids:
        out += deployment(by_id[model_id])
    names = set(model_ids)
    if with_budget_group and all(m in by_id for m, _ in BUDGET_GROUP):
        out.append("  # Model group 'budget': two cheap deployments behind one name, weighted 3:1.")
        for model_id, weight in BUDGET_GROUP:
            out += deployment(by_id[model_id], name="budget", weight=weight)
        names.add("budget")
    aliases = {a: t for a, t in ALIASES.items() if t in names}
    fallbacks = [(src, [d for d in dst if d in names]) for src, dst in FALLBACKS if src in names]
    fallbacks = [(src, dst) for src, dst in fallbacks if dst]
    out += [
        "",
        "router_settings:",
        "  routing_strategy: simple-shuffle",
        "  model_group_alias: " + json.dumps(aliases),
        "  fallbacks: " + json.dumps([{src: dst} for src, dst in fallbacks]),
        "  num_retries: 2",
        "  timeout: 600",
        "",
        "litellm_settings:",
        "  drop_params: true",
        "",
        "general_settings:",
        "  master_key: os.environ/LITELLM_MASTER_KEY",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--catalog", help="read a saved catalog JSON instead of the live endpoint")
    parser.add_argument("--all-chat", action="store_true", help="include every chat model in the catalog")
    parser.add_argument("--models", help="comma-separated model IDs (default: a curated set of 10)")
    args = parser.parse_args(argv)
    catalog = load_catalog(args.catalog)
    if args.all_chat:
        ids = [m["id"] for m in catalog["items"] if m.get("category") == "chat"]
    elif args.models:
        ids = [m.strip() for m in args.models.split(",") if m.strip()]
    else:
        ids = DEFAULT_MODELS
    sys.stdout.write(render(catalog, ids))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
